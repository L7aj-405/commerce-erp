export type FollowUpPriority = 'low' | 'normal' | 'high';
export type FollowUpStatus = 'open' | 'completed' | 'cancelled';

export type FollowUpItem = {
    id: number;
    title: string;
    note: string | null;
    priority: FollowUpPriority;
    status: FollowUpStatus;
    /** Organization-local calendar date (YYYY-MM-DD). */
    due_date: string | null;
    /** Organization-local time (HH:MM); null for date-only work. */
    due_time: string | null;
    due_at: string | null;
    is_overdue: boolean;
    is_today: boolean;
    /** null = "Unassigned" (only visible to follow_ups.manage_all). */
    assignee: { id: number; name: string } | null;
    customer: { id: number; name: string } | null;
    /** can_open: the viewer may open it (via /work/{id}/open-quotation, which switches store if needed). */
    quotation: { id: number; number: string | null; store_id: number; can_open: boolean } | null;
    /** W4.4: linked invoice (exclusive with quotation), opened via /work/{id}/open-invoice. */
    invoice: { id: number; number: string | null; can_open: boolean } | null;
    /** W4.5: linked sales order (receivable), opened via /work/{id}/open-sales-order. */
    sales_order: { id: number; number: string | null; can_open: boolean } | null;
    completed_at: string | null;
    cancelled_at: string | null;
    outcome_note: string | null;
    /** W2: when the current occurrence's due reminder was delivered (UTC ISO). */
    notified_at: string | null;
    /** W3: generated by this recurring rule (NULL for manual work). */
    recurring_rule_id: number | null;
    version: number;
    can_manage: boolean;
};

export type FollowUpContext = {
    today: string;
    timezone: string;
    timezone_configured: boolean;
    can_create: boolean;
    can_manage_all: boolean;
    current_user_id: number;
    assignees: { id: number; name: string }[];
    /** W3: active templates that pre-fill the create form. */
    templates: FollowUpTemplate[];
};

export type FollowUpTemplate = {
    id: number;
    name: string;
    title: string;
    default_note: string | null;
    default_priority: FollowUpPriority;
    default_due_offset_days: number | null;
    default_time: string | null;
    active: boolean;
};

export type RecurrenceFrequency = 'daily' | 'weekly' | 'monthly';

export type RecurringRule = {
    id: number;
    title: string;
    note: string | null;
    priority: FollowUpPriority;
    frequency: RecurrenceFrequency;
    interval_count: number;
    /** ISO weekdays, 1 = Monday … 7 = Sunday. */
    weekdays: number[];
    month_day: number | null;
    /** Organization-local HH:MM; null = date-only occurrences. */
    local_time: string | null;
    starts_on: string;
    ends_on: string | null;
    max_occurrences: number | null;
    occurrences_generated: number;
    status: 'active' | 'paused' | 'ended';
    status_reason: string | null;
    next_occurrence_on: string | null;
    assignee: { id: number; name: string } | null;
    customer: { id: number; name: string } | null;
    quotation: { id: number; number: string | null } | null;
    version: number;
    can_manage: boolean;
};

export type FollowUpPanelData = {
    items: FollowUpItem[];
    context: FollowUpContext;
    prefill: { customer_id: number | null; quotation_id: number | null };
    /** W3.1: display labels for the prefilled links (server-resolved). */
    prefill_labels: { customer: string | null; quotation: string | null };
} | null;

/** Calendar arithmetic on YYYY-MM-DD strings, independent of the browser timezone. */
export function addDays(date: string, days: number): string {
    const [y, m, d] = date.split('-').map(Number);
    return new Date(Date.UTC(y, m - 1, d + days)).toISOString().slice(0, 10);
}
